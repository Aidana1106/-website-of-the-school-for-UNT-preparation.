async function addENTQuestions() {
  try {
    console.log('=== ДОБАВЛЕНИЕ ВОПРОСОВ В ЕНТ ТЕСТ ===\n');
    
    // 1. Найти ЕНТ тест
    const entTest = await db.query(
      "SELECT id, total_questions FROM tests WHERE subject = 'ent' AND is_main_test = 1 LIMIT 1",
      []
    );
    
    if (entTest.rows.length === 0) {
      console.log('❌ ЕНТ тест не найден!');
      console.log('Сначала запустите: node create-ent-test.js');
      process.exit(1);
    }
    
    const testId = entTest.rows[0].id;
    const existingQuestions = entTest.rows[0].total_questions || 0;
    
    console.log(`✅ Найден ЕНТ тест (ID: ${testId})`);
    console.log(`   Текущее количество вопросов: ${existingQuestions}`);
    
    // 2. Проверить, есть ли уже вопросы
    const questionsCheck = await db.query(
      'SELECT COUNT(*) as count FROM test_questions WHERE test_id = ?',
      [testId]
    );
    
    if (questionsCheck.rows[0].count > 0) {
      console.log(`\n⚠️ В тесте уже есть ${questionsCheck.rows[0].count} вопросов.`);
      console.log('Удалить существующие вопросы и добавить новые? (y/n)');
      // Для автоматизации - удаляем старые вопросы
      console.log('Удаление старых вопросов...');
      await db.query('DELETE FROM test_questions WHERE test_id = ?', [testId]);
    }
    
    // 3. Добавить все вопросы
    console.log(`\n📝 Добавление ${entQuestions.length} вопросов...`);
    
    for (let i = 0; i < entQuestions.length; i++) {
      const question = entQuestions[i];
      
      await db.query(
        `INSERT INTO test_questions (test_id, question_text, question_type, options, correct_answer, points, question_order) 
         VALUES (?, ?, ?, ?, ?, ?, ?)`,
        [
          testId,
          question.text,
          'single_choice',
          JSON.stringify(question.options),
          String(question.correct), // Исправлено: убрал JSON.stringify
          1,
          i
        ]
      );
    }
    
    // 4. Обновить total_questions в тесте
    await db.query(
      'UPDATE tests SET total_questions = ? WHERE id = ?',
      [entQuestions.length, testId]
    );
    
    console.log(`\n✅ ГОТОВО! Добавлено ${entQuestions.length} вопросов в ЕНТ тест.`);
    console.log(`\n📊 Статистика:`);
    console.log(`   - Математикалық сауаттылық: 40 вопросов`);
    console.log(`   - Оқу сауаттылығы: 10 вопросов`);
    console.log(`   - Қазақстан тарихы: 10 вопросов`);
    console.log(`   - Информатика: 40 вопросов`);
    console.log(`   - Математика: 40 вопросов`);
    console.log(`   - Всего: ${entQuestions.length} вопросов`);
    image.png
    process.exit(0);
  } catch (error) {
    console.error('\n❌ ОШИБКА:', error.message);
    console.error(error.stack);
    process.exit(1);
  }
}

